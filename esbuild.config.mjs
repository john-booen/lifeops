import esbuild from "esbuild";
import process from "node:process";
import builtins from "builtin-modules";
import { assertFreshBundleOutput, bundleOptions } from "./scripts/bundle-options.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const options = bundleOptions(process.argv.slice(2));
await assertFreshBundleOutput(options);
const prod = options.production;
const watch = options.watch;

const context = await esbuild.context({
  banner: {
    js: banner
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  metafile: true,
  platform: "node",
  external: [
    "obsidian",
    "electron",
    "proxy-agent",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  minifyWhitespace: prod,
  minifySyntax: prod,
  minifyIdentifiers: prod,
  treeShaking: true,
  outfile: options.outfile
});

if (watch) {
  await context.watch();
  console.log("Watching for changes...");
} else {
  await context.rebuild();
  await context.dispose();
}
