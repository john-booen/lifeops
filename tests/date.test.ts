import { describe, expect, it } from "vitest";
import { normalizeJournalDate } from "../src/date";
import { resolveStatsRange, type StatsRange } from "../src/features/stats/stats";

describe("Chinese calendar dates", () => {
  it.each([
    ["2026-11-12", "今天", "2026-11-12"],
    ["2026-11-12", "昨晚", "2026-11-11"],
    ["2026-11-12", "大前天", "2026-11-09"],
    ["2026-11-12", "大后天", "2026-11-15"],
    ["2026-11-12", "这周一", "2026-11-09"],
    ["2026-11-12", "本周四", "2026-11-12"],
    ["2026-11-12", "下周三", "2026-11-18"],
    ["2026-11-12", "下周天", "2026-11-22"],
    ["2026-11-12", "周末", "2026-11-14"],
    ["2026-11-12", "下周末", "2026-11-21"],
    ["2026-11-12", "月底", "2026-11-30"],
    ["2026-11-12", "二十四号", "2026-11-24"],
    ["2026-11-12", "１２月３日", "2026-12-03"],
    ["2026-11-12", "十一月二十日", "2026-11-20"],
    ["2026-11-12", "没有日期", ""],
    ["2026-11-12", "11月31日", ""],
    ["2026-11-12", "下周八", ""],
    ["2026-11-12", "12十号", ""],
    ["2026-11-12", "2026-02-29", ""],
    ["2026-11-12", "2026-11-29", "2026-11-29"],
    ["2026-12-31", "大后天", "2027-01-03"],
    ["2026-12-31", "大前天", "2026-12-28"],
    ["2026-12-31", "本周日", "2027-01-03"],
    ["2026-12-31", "下周1", "2027-01-04"],
    ["2026-12-31", "周末", "2027-01-02"],
    ["2026-12-31", "下个周末", "2027-01-09"],
    ["2026-12-31", "本月底", "2026-12-31"],
    ["2026-12-31", "31号", "2026-12-31"],
    ["2026-12-31", "十三月七日", ""],
    ["2028-02-27", "大后天", "2028-03-01"],
    ["2028-02-27", "周末", "2028-02-27"],
    ["2028-02-27", "本周六", "2028-02-26"],
    ["2028-02-27", "下周二", "2028-02-29"],
    ["2028-02-27", "下周末", "2028-03-04"],
    ["2028-02-27", "月底", "2028-02-29"],
    ["2028-02-27", "29号", "2028-02-29"],
    ["2028-02-27", "30号", ""],
    ["2028-02-27", "2月29日", "2028-02-29"],
    ["2028-02-27", " 2月二十七号 ", "2028-02-27"]
  ])("resolves %s + %s to %s", (base, input, expected) => {
    expect(normalizeJournalDate(input, base)).toBe(expected);
  });

  it("resolves both statistics boundaries and rejects invalid or reversed ranges", () => {
    const now = new Date(2026, 10, 12, 12);
    expect(resolveStatsRange({ from: "这周一", to: "月底" }, now)).toEqual({ from: "2026-11-09", to: "2026-11-30" });
    expect(() => resolveStatsRange({ from: "下周三", to: "本周五" }, now)).toThrow("开始日期不能晚于结束日期");
    expect(() => resolveStatsRange({ from: "11月31日", to: "月底" }, now)).toThrow("有效的起止日期");
  });

  it.each(['2028-02-29..2028-03-02','2028-02-29/2028-03-02'] as const)('keeps valid leap-day interval %s exact across months',interval=>{
    expect(resolveStatsRange(interval,new Date(2026,10,12,12))).toEqual({from:'2028-02-29',to:'2028-03-02'});
  });
  it.each(['2026-02-29..2026-03-01','2026-11-31/2026-12-02','2026-11-08..2026-11-02','x2026-11-02..2026-11-08','2026-11-02/2026-11-08x'])('rejects invalid interval %s rather than substituting current dates',interval=>{
    expect(()=>resolveStatsRange(interval as StatsRange,new Date(2026,10,12,12))).toThrow();
  });
});
